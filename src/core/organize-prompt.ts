import type { ChatMessage } from "./ai";

/**
 * 文献整理：把 OCR 出来的版面文本还原成 Markdown。
 *
 * 原则是「保真」：只做结构修复（标题层级、断词、页眉页脚），
 * 不改写、不概括、不删内容。英文文献逐段附中文译文。
 */
export function organizeChunkMessages(input: {
  title: string;
  bilingual: boolean;
  chunkIndex: number;
  chunkTotal: number;
  text: string;
  retry?: boolean;
}): ChatMessage[] {
  const rules = [
    "你在整理一份学术文献的 OCR 文本。只做排版还原，不改写内容。",
    "",
    `文献标题：${input.title}`,
    `这是第 ${input.chunkIndex}/${input.chunkTotal} 段。`,
    "",
    "任务：",
    "1. 还原 Markdown 结构：章节标题用 ## / ###，正文按语义分段。",
    "2. OCR 的硬换行要接回成完整段落；修复断词与行尾连字符（例如 emotion- al → emotional）。",
    "3. 删除页眉、页脚、页码、重复的期刊名；保留正文里的编号、公式、变量名。",
    "4. 形如 [FIG:图 1|第 3 页] 的占位符必须原样保留，不要改写、不要移动位置。",
    "5. 形如 <!-- 第 N 页 --> 的页标记直接删除。",
    "6. 不要概括、不要删减、不要补充原文没有的内容；不确定的乱码保留原样。",
    input.bilingual
      ? "7. 逐段翻译成中文：先输出原文段落，空一行，再输出一行 `> 中文：译文`。译文要准确，术语前后一致。"
      : "7. 只输出原文，不要翻译。",
    "8. 只输出整理后的 Markdown，不要写「以下是」这类前言。",
    "9. 标题只输出一行：不要写成 `## # 标题` 这种多重井号，也不要在正文里重复文献标题。",
    "10. 长段落如果明显吞并了多个自然段，请按语义拆开；不要制造只有一个短句的碎段。",
    "11. 不要自己发明章节标题：只有原文里出现的标题才可以输出；跨页接续的段落要合并成一个完整段落。",
    "12. 图表标题（Table/Figure/图/表 开头）只输出一次：保留英文原文，不要另起中文标题，也不要在表格前后重复。",
    "13. 参考文献列表（作者 + 年份 + 标题 的条目）保留原文，不翻译，不要逐条加中文。",
    input.retry
      ? "11. 重要：上一次输出明显不完整。这一次必须完整输出本段全部内容，不要省略、不要概括。"
      : "",
  ];

  return [
    {
      role: "system",
      content:
        "你是严谨的学术排版助手。你的输出会被学生当作原文阅读，所以任何改写、删减或编造都是严重错误。",
    },
    { role: "user", content: `${rules.join("\n")}\n\n---\n\n${input.text}` },
  ];
}
